import React, { useState } from 'react';
import { demoAlerts } from '../lib/demoData';
import { Bell, ArrowRight } from 'lucide-react';
import { RiskBadge } from '../components/ui/RiskBadge';
import { Link } from 'react-router-dom';

export const Alerts: React.FC = () => {
  const [severityFilter, setSeverityFilter] = useState('ALL');
  const [alertsList, setAlertsList] = useState(demoAlerts);

  const filtered = alertsList.filter((a) => {
    if (severityFilter !== 'ALL' && a.severity !== severityFilter) return false;
    return true;
  });

  const handleDismiss = (id: string) => {
    setAlertsList((prev) => prev.filter((a) => a.id !== id));
  };

  return (
    <div className="space-y-6 max-w-7xl mx-auto">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-gray-200/80 dark:border-gray-800">
        <div>
          <div className="flex items-center gap-2">
            <Bell className="w-5 h-5 text-rose-500" />
            <h2 className="text-xl font-bold text-gray-900 dark:text-white tracking-tight">
              Live Intelligence Alerts Queue
            </h2>
          </div>
          <p className="text-xs text-gray-500 dark:text-gray-400 mt-1">
            Real-time triggers generated by continuous graph monitoring, screening holds, and onboarding collisions
          </p>
        </div>

        <div className="flex items-center gap-1.5 bg-white dark:bg-gray-800 p-1 rounded-xl border border-gray-200/80 dark:border-gray-700 shadow-2xs">
          {['ALL', 'CRITICAL', 'HIGH', 'MEDIUM'].map((lvl) => (
            <button
              key={lvl}
              onClick={() => setSeverityFilter(lvl)}
              className={`px-3 py-1 rounded-lg text-xs font-semibold transition-all ${
                severityFilter === lvl
                  ? 'bg-rose-500 text-white shadow-xs'
                  : 'text-gray-600 dark:text-gray-400 hover:text-gray-900 dark:hover:text-white'
              }`}
            >
              {lvl}
            </button>
          ))}
        </div>
      </div>

      {/* Alerts List */}
      <div className="space-y-3.5">
        {filtered.map((al) => (
          <div
            key={al.id}
            className="p-5 rounded-2xl bg-white dark:bg-[#1C2434] border border-gray-200/80 dark:border-gray-800 hover:border-gray-300 dark:hover:border-gray-700 transition-all flex flex-col md:flex-row md:items-center justify-between gap-4 shadow-[0_1px_3px_rgba(0,0,0,0.04)]"
          >
            <div className="space-y-2 flex-1">
              <div className="flex flex-wrap items-center gap-2">
                <RiskBadge level={al.severity} size="sm" />
                <span className="px-2.5 py-0.5 rounded-full bg-gray-100 dark:bg-gray-800 text-[10px] font-bold text-gray-700 dark:text-gray-300 border border-gray-200 dark:border-gray-700">
                  {al.alert_type}
                </span>
                <span className="text-[11px] text-gray-400">
                  {new Date(al.created_at).toLocaleString()}
                </span>
              </div>
              <h3 className="text-sm font-bold text-gray-900 dark:text-white">{al.title}</h3>
              <p className="text-xs text-gray-500 dark:text-gray-400 leading-relaxed max-w-3xl">
                {al.description}
              </p>
            </div>

            <div className="flex items-center gap-3">
              <button
                onClick={() => handleDismiss(al.id)}
                className="px-3.5 py-2 rounded-xl bg-gray-50 dark:bg-gray-800 hover:bg-gray-100 dark:hover:bg-gray-700 text-xs font-semibold text-gray-600 dark:text-gray-300 border border-gray-200 dark:border-gray-700 transition-colors"
              >
                Dismiss
              </button>
              <Link
                to="/investigations/INV-2026-PHANTOM-001"
                className="flex items-center gap-1.5 px-4 py-2 rounded-xl bg-rose-600 hover:bg-rose-500 text-white text-xs font-bold transition-all shadow-md shadow-rose-600/20"
              >
                Escalate Case <ArrowRight className="w-3.5 h-3.5" />
              </Link>
            </div>
          </div>
        ))}
      </div>
    </div>
  );
};
